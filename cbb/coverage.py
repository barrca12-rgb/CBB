"""Data check: what the hoopR game data covers, season by season.

    python -m cbb.coverage                      # 2012-2026, writes DATA.md
    python -m cbb.coverage --start 2015 --end 2020
"""
from __future__ import annotations

import argparse
import os

from . import data, teams

OUT = os.path.join(os.path.dirname(__file__), "..", "DATA.md")


def report(start: int, end: int) -> str:
    g, t = data.load(range(start, end + 1))
    s = g.groupby("season").agg(
        games=("game_id", "size"),
        neutral=("neutral", "mean"),
        conf=("conf_game", "mean"),
        postseason=("season_type", lambda x: int((x == 3).sum())),
        first=("date", "min"),
        last=("date", "max"),
        pace=("pace", "mean"),
    )
    s.insert(1, "teams", t.groupby("season")["team_id"].nunique())
    f = t.groupby("season")[["ppp", "efg", "tov_rate", "orb_rate", "ft_rate"]].mean()
    s = s.join(f)
    s["first"] = s["first"].dt.date
    s["last"] = s["last"].dt.date

    names = teams.load()
    latest = t[t["season"] == t["season"].max()]["team_id"].unique()
    unmatched = sorted(set(latest) - set(names["espn_id"]))

    lines = [
        "# Data coverage",
        "",
        f"Generated by `python -m cbb.coverage --start {start} --end {end}`. Division I vs Division I completed "
        "games from hoopR (ESPN). `season` is the year the season ends. Possessions use FGA - OREB + TO + "
        f"{data.FT_WEIGHT} x FTA, averaged over both teams; pace is per 40 minutes.",
        "",
        "| season | games | teams | neutral | conf games | postseason | first | last | pace | pts/100 | eFG% | TO% | OREB% | FT rate |",
        "|---:|---:|---:|---:|---:|---:|---|---|---:|---:|---:|---:|---:|---:|",
    ]
    for season, r in s.iterrows():
        lines.append(
            f"| {season} | {r.games:,} | {r.teams} | {r.neutral:.1%} | {r.conf:.1%} | {r.postseason} | {r['first']} | "
            f"{r['last']} | {r.pace:.1f} | {r.ppp:.1f} | {r.efg:.1%} | {r.tov_rate:.1%} | {r.orb_rate:.1%} | "
            f"{r.ft_rate:.3f} |")
    lines += [
        "",
        f"Team names: {len(names)} teams in `data/teams.csv`, {names['kenpom'].notna().sum()} with a KenPom name. "
        f"Teams in the {t['season'].max()} games with no entry: {len(unmatched)}"
        + (f" ({', '.join(map(str, unmatched))})" if unmatched else "") + ".",
    ]
    return "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--start", type=int, default=2012)
    ap.add_argument("--end", type=int, default=2026)
    a = ap.parse_args()
    md = report(a.start, a.end)
    with open(OUT, "w") as f:
        f.write(md)
    print(md)


if __name__ == "__main__":
    main()
